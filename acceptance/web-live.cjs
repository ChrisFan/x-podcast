const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('/Users/chris/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = path.resolve(__dirname, '..');
const secret = JSON.parse(fs.readFileSync(path.join(root,'.local/deployment-secrets.json'),'utf8'));
const pid = JSON.parse(fs.readFileSync(path.join(root,'.local/acceptance-podcast.json'),'utf8')).id;
(async()=>{
  const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const page = await context.newPage();
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('https://alu-designer.pawlpixel.com/podcast/',{waitUntil:'networkidle'});
  await page.screenshot({path:path.join(__dirname,'web-welcome.png'),fullPage:true});
  await page.locator('#account').click();
  await page.locator('#email').fill('mvp-owner@example.invalid');
  await page.locator('#password').fill(secret.acceptance_password);
  await page.locator('#auth-submit').click();
  await page.locator('#auth-dialog').waitFor({state:'hidden'});
  await page.locator('#account').filter({hasText:'退出'}).waitFor();
  await page.locator('.card').filter({hasText:'雨夜旅馆 · 云端首夜'}).waitFor();
  await page.screenshot({path:path.join(__dirname,'web-library.png'),fullPage:true});
  console.log('PASS real browser login and shared cloud library');
  await page.locator('[data-tab="create"]').click();
  await page.locator('#new-draft').click();
  await page.locator('#title').fill('Web 验收草稿');
  await page.locator('#editor button[type="submit"]').click();
  await page.waitForFunction(()=>document.querySelector('#editing-id').value.length>0);
  const draft=await page.locator('#editing-id').inputValue();
  await page.screenshot({path:path.join(__dirname,'web-studio.png'),fullPage:true});
  await page.locator('[data-tab="library"]').click();
  await page.locator(`[data-action="edit"][data-id="${draft}"]`).waitFor();
  page.once('dialog',d=>d.accept());
  await page.locator(`[data-action="delete"][data-id="${draft}"]`).click();
  await page.locator(`[data-action="edit"][data-id="${draft}"]`).waitFor({state:'detached'});
  console.log('PASS browser draft save, library sync, and delete');
  await page.locator(`[data-action="play"][data-id="${pid}"]`).waitFor({timeout:180000});
  await page.locator(`[data-action="play"][data-id="${pid}"]`).click();
  await page.waitForFunction(()=>{const a=document.querySelector('#audio');return a.duration>0&&!a.paused;},{timeout:90000});
  const start=await page.locator('#audio').evaluate(a=>a.currentTime);
  await page.waitForTimeout(2000);
  const later=await page.locator('#audio').evaluate(a=>a.currentTime);
  if(later<=start) throw Error('Audio clock did not advance');
  await page.locator('#forward15').click();
  await page.locator('#timer').selectOption('15');
  await page.screenshot({path:path.join(__dirname,'web-player.png'),fullPage:true});
  console.log('PASS real MP3 decode/playback, seek, sleep timer');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(__dirname,'web-mobile.png'),fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  if(overflow) throw Error('Mobile layout horizontal overflow');
  await page.locator('#account').click();
  await page.waitForFunction(()=>document.querySelector('#audio').paused);
  if(await page.locator('#token-value').textContent()) throw Error('Token still visible after logout');
  if(errors.length) throw Error('Browser JS errors: '+errors.join('; '));
  fs.writeFileSync(path.join(__dirname,'web-live-results.json'),JSON.stringify({passed:['login','shared-library','create-draft','delete-draft','mp3-playback-clock','seek','timer','mobile-no-overflow','logout-stops-audio'],js_errors:errors},null,2));
  console.log('PASS logout stops playback, mobile layout fits, no JavaScript errors');
  await browser.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
